// Chunk an array into groups of `size`.
function chunk(arr, size) {
  const out = [];
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size));
  return out;
}

// Build the full exercise object a தேர்வு renders in the DynamicExerciseModal,
// borrowing the side panels from `sourceSet` (the matching puram exercise set).
export function buildTervuExercise(cfg, sourceSet) {
  const questions = [
    {
      // primaryTitle left empty: the centre-header already shows the தேர்வு name
      // (via the modal's `title` prop), so an h3 here would repeat it.
      type: 'title',
      primaryTitle: '',
      primaryInstruction: cfg.page1Instruction,
      secondaryTitle: '',
      paadal: cfg.paadal,
      secondaryInstruction: '',
    },
    {
      type: 'truefalse',
      paadal: cfg.paadal,
      primaryInstruction: 'இப்பாடலை ஒருமுறை மனத்திற்குள் வாசித்துக் கொள்ளுங்கள்.',
      question: 'வாசித்துவிட்டீர்களா ?',
      redQuestion: true,
      answer: 'ஆம்',
      wrongMessage: 'இல்லை. இப்பாடலை மீண்டும் ஒருமுறை கவனமாக வாசித்துவிட்டு மீண்டும் முயற்சி செய்யுங்கள்.',
    },
  ];

  // Max 4 blanks per page; remaining blanks flow onto following pages.
  // Every fillblanks page uses the physical-keyboard transliteration input
  // (type English → live Tamil, suggestions, Enter→next blank, copy-paste).
  chunk(cfg.blanks, 4).forEach((group, gi) => {
    questions.push({
      type: 'fillblanks',
      paadal: cfg.paadal,
      question: gi === 0 ? cfg.fillPrompt : '',
      startNumber: gi * 4 + 1,
      blanks: group,
      suggestions: SUGGESTIONS,
      keyboardMode: 'transliterate',
    });
  });

  return {
    leftButtons: sourceSet.leftButtons || [],
    rightContent: sourceSet.rightContent || {},
    rightContentEnglish: sourceSet.rightContentEnglish || {},
    questions,
  };
}

// Resolve the source set for a தேர்வு from the fetched { unitKey: sets[] } map,
// preferring the configured unit+index but falling back to a paadal-first-line
// match so it still works if sets were reordered.
export function resolveSourceSet(cfg, exercisesMap) {
  const list = exercisesMap?.[cfg.sourceUnit] || [];
  const byIndex = list[cfg.sourceIndex];
  const firstLine = cfg.paadal.split('\n')[0].trim();
  const matches = (set) =>
    (set?.questions || []).some(
      (q) => q.type === 'title' && typeof q.paadal === 'string' &&
             q.paadal.trim().startsWith(firstLine)
    );
  if (byIndex && matches(byIndex)) return byIndex;
  for (const key of Object.keys(exercisesMap || {})) {
    const found = (exercisesMap[key] || []).find(matches);
    if (found) return found;
  }
  return byIndex || null;
}
